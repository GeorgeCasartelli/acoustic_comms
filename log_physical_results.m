function log_physical_results(filename, phyParams, ber, ser, snr, throughput)

    if ~isfile(filename)

        fid = fopen(filename, 'w');

        fprintf(fid, ...
['test,trial,ber,ser,snr,throughput,' ...
 'distance,volume,' ...
 'txAngle,rxAngle,' ...
 'blocked,blockerType,' ...
 'reflectionMode,' ...
 'modscheme,useCoding,' ...
 'notes\n']);

        fclose(fid);

    end

    fid = fopen(filename, 'a');

    fprintf(fid, ...
['%s,%d,%.6f,%.6f,%.4f,%.4f,' ...
 '%.2f,%d,' ...
 '%.1f,%.1f,' ...
 '%d,%s,' ...
 '%s,' ...
 '%s,%d,' ...
 '%s\n'], ...
        phyParams.test, ...
        phyParams.trial, ...
        ber, ...
        ser, ...
        snr, ...
        throughput, ...
        phyParams.distance, ...
        phyParams.volume, ...
        phyParams.txAngle, ...
        phyParams.rxAngle, ...
        phyParams.blocked, ...
        phyParams.blockerType, ...
        phyParams.reflectionMode, ...
        phyParams.modscheme, ...
        phyParams.useCoding, ...
        phyParams.notes);

    fclose(fid);

end